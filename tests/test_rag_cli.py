"""Run one RAG conversation turn from the VS Code terminal.

Examples:
    python tests/test_rag_cli.py --message "Can I return my laptop after 20 days?"
    python tests/test_rag_cli.py --message "What about opened packaging?" --history-file tests/history.json
    python tests/test_rag_cli.py --message "What are the laptop specifications?" --json
"""

import argparse
import json
import os
import sys
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from app.graph.graph import workflow
from app.graph.state import SupportState


def load_history(path: str | None) -> list[dict[str, str]]:
    if not path:
        return []

    history_path = Path(path)
    if not history_path.is_absolute():
        history_path = ROOT / history_path

    with history_path.open(encoding="utf-8") as history_file:
        history = json.load(history_file)

    if not isinstance(history, list):
        raise ValueError("History file must contain a JSON array.")
    return history


def build_state(message: str, tenant_id: str, conversation_id: str, history: list[dict[str, str]]) -> SupportState:
    return SupportState(
        query=message,
        tenant_id=tenant_id,
        conversation_id=conversation_id,
        conversation_history=history,
        intent="",
        rewritten_query="",
        retrieved_docs=[],
        reranked_docs=[],
        evidence="",
        evidence_score=0.0,
        evidence_reason="",
        missing_info=[],
        answer="",
        sources=[],
        citations=[],
        confidence=0.0,
        needs_human=False,
        grounded=False,
        escalated=False,
    )


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Test the customer-support RAG workflow from a command shell.")
    parser.add_argument("--message", required=True, help="Customer question to send to the RAG workflow.")
    parser.add_argument("--tenant-id", default="tenant-123", help="Tenant identifier used by the vector store.")
    parser.add_argument("--conversation-id", default=None, help="Conversation ID. A random ID is generated by default.")
    parser.add_argument("--history-file", help="JSON file containing previous conversation messages.")
    parser.add_argument("--json", action="store_true", dest="as_json", help="Print the complete response as JSON.")
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    try:
        history = load_history(args.history_file)
        state = build_state(
            message=args.message,
            tenant_id=args.tenant_id,
            conversation_id=args.conversation_id or f"cli-{uuid.uuid4().hex[:8]}",
            history=history,
        )
        result = workflow.invoke(state)
    except Exception as error:
        print(f"RAG test failed: {error}", file=sys.stderr)
        return 1

    response = {
        "answer": result.get("answer", ""),
        "intent": result.get("intent", "other"),
        "confidence": float(result.get("confidence", result.get("evidence_score", 0.0))),
        "citations": result.get("citations", []),
        "sources": result.get("sources", []),
        "needs_human": bool(result.get("needs_human", result.get("escalated", False))),
        "escalated": bool(result.get("escalated", False)),
    }

    if args.as_json:
        print(json.dumps(response, indent=2))
    else:
        print(f"Answer: {response['answer']}")
        print(f"Intent: {response['intent']}")
        print(f"Confidence: {response['confidence']:.2f}")
        print(f"Needs human: {response['needs_human']}")
        print(f"Citations: {json.dumps(response['citations'])}")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
